def probe(text):
    """实际解析一条，返回 (特征种类概要, 关键尺寸, 告警数)。"""
    try:
        r = NLP.parse(text)
    except Exception as e:
        return "解析异常: %s" % str(e)[:40], "", 0
    kinds = []
    dims = []
    for f in r.doc.features:
        kinds.append(f.kind)
        p = f.params or {}
        for k in ("radius", "diameter", "height", "pitch_d", "outer_d", "teeth",
                  "grooves", "groove_type", "tooth_type", "margin", "depth"):
            v = p.get(k)
            if v is None or isinstance(v, (dict, list, tuple)):
                continue
            if isinstance(v, float):
                if abs(v - round(v)) < 1e-9:
                    v = int(round(v))
                else:
                    v = round(v, 3)
            dims.append("%s=%s" % (k, v))
    return "+".join(kinds) or "（无特征）", " ".join(dims[:8]), len(r.warnings)


def main():
    txt = []
    md = ["# 零件 AI 提示词测试报告", "",
          "本报告由 `tools/make_test_prompts.py` 生成：**每条都实际跑过**，",
          "列出解析出的特征与关键尺寸，便于与期望值对照。", ""]
    n_ok = n_total = 0
    for group, text, expect in CASES:
        if text is None:
            txt.append("")
            txt.append("=" * 66)
            txt.append(group)
            txt.append("=" * 66)
            md.append("")
            md.append("## %s" % group)
            md.append("")
            md.append("| # | 提示词 | 解析结果 | 关键尺寸 | 期望 |")
            md.append("|---|---|---|---|---|")
            continue
        n_total += 1
        kinds, dims, warns = probe(text)
        ok = kinds != "（无特征）" and not kinds.startswith("解析异常")
        n_ok += 1 if ok else 0
        txt.append("%-2d. %s" % (n_total, text))
        md.append("| %d | `%s` | %s | %s | %s |"
                  % (n_total, text, kinds, dims or "—", expect or ""))
    txt.append("")
    txt.append("=" * 66)
    txt.append("共 %d 条" % n_total)
    txt.append("=" * 66)

    out_txt = os.path.join(ROOT, "kb", "test_prompts.txt")
    with io.open(out_txt, "w", encoding="utf-8") as f:
        f.write("\n".join(txt) + "\n")
    out_md = os.path.join(ROOT, "reports", "提示词测试报告.md")
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    md.insert(4, "**实测：%d/%d 条能解析出特征。**" % (n_ok, n_total))
    with io.open(out_md, "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")

    print("共 %d 条，其中 %d 条解析出特征（%d 条无特征）"
          % (n_total, n_ok, n_total - n_ok))
    print("已写入 %s" % out_txt)
    print("已写入 %s" % out_md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
