def run(text):
    t0 = time.time()
    try:
        r = NLP.parse(text)
    except Exception as e:
        return None, '解析异常: %s' % str(e)[:44], 0
    if not r.ok:
        return None, '未识别', 0
    try:
        body = r.doc.build(deadline=time.time() + 15)
    except Exception as e:
        return None, '构建中止: %s' % str(e)[:40], 0
    bb = K.bbox(body)
    size = (round(bb[3] - bb[0], 1), round(bb[4] - bb[1], 1), round(bb[5] - bb[2], 1)) if bb else None
    return size, '', len(r.doc.features)


def fmt(s):
    return '（无）' if not s else '%.4g × %.4g × %.4g' % s


def close(a, b, tol=0.03):
    if a is None or b is None:
        return None
    return all(abs(x - y) <= max(tol * y, 0.35) for x, y in zip(a, b))


