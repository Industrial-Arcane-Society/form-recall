    A('')
    A('**图例**：✅ 正常 ｜ ⚠️ 能建出来但和预期不符 ｜ ❌ 没建出来')
    A('')
    A('建好的模型可以在 ' + T + 'artifacts/model-shots/' + T + ' 里对照着看形状对不对。')
    A('')

    tot = ok = 0
    summary = []
    for group, items in CASES:
        A('## ' + group)
        A('')
        A('| # | 中文描述 | 期望外形 (mm) | 实测尺寸 (mm) | 面片 | 结果 | 怎么检查 |')
        A('|---|---|---|---|---|---|---|')
        gok = 0
        for i, (phrase, exp, how) in enumerate(items, 1):
            dim, nf, dt = run(phrase)
            tot += 1
            vague = exp is None or any(e is None for e in exp)
            if dim is None:
                mark, got = '❌', '没建出来'
            elif vague:
                mark, got = '✅', '%.1f × %.1f × %.1f' % dim
                ok += 1
                gok += 1
            else:
                good = all(abs(g - e) <= max(0.02 * e, 1e-6) for g, e in zip(dim, exp))
                mark = '✅' if good else '⚠️'
                got = '%.1f × %.1f × %.1f' % dim
                if good:
                    ok += 1
                    gok += 1
                else:
                    got += ' (与预期不符)'
            exp_s = '—' if vague else '%.1f × %.1f × %.1f' % exp
            A('| %d | ' % i + T + phrase + T + ' | %s | %s | %d | %s | %s |'
              % (exp_s, got, nf, mark, how))
        A('')
        summary.append((group, gok, len(items)))
        print('  %-30s %2d/%2d' % (group, gok, len(items)), flush=True)

    A('---')
    A('')
    A('## 汇总')
    A('')
    A('| 分组 | 通过 |')
    A('|---|---|')
    for g, a, b in summary:
        A('| %s | %d / %d |' % (g, a, b))
    A('| **合计** | **%d / %d （%.0f%%）** |' % (ok, tot, 100.0 * ok / max(1, tot)))
    A('')
    A('## 重点看什么')
    A('')
    A('1. **齿形**：斜齿轮的齿要从侧面能看出是斜的，锥齿轮的齿高要沿轴向收小。')
