def blocks(doc):
    for child in doc.element.body.iterchildren():
        if child.tag == qn("w:p"):
            yield Paragraph(child, doc)
        elif child.tag == qn("w:tbl"):
            yield Table(child, doc)


def set_text(par: Paragraph, text: str):
    """替换段落文字但保留原有格式；支持 `**加粗**` 片段（转成 Word 真加粗，不留下星号）。"""
    runs = par.runs
    if not runs:
        par.add_run(text)
        return
    base = runs[0]
    base_rpr = base._element.find(qn("w:rPr"))
    for r in runs[1:]:
        r._element.getparent().remove(r._element)
    parts = re.split(r"\*\*(.+?)\*\*", text)      # 偶数=普通，奇数=加粗
    segs = [(parts[0], False)]
    for i, seg in enumerate(parts[1:], start=1):
        segs.append((seg, i % 2 == 1))
    base.text = segs[0][0]
    if segs[0][1]:
        base.bold = True
    for seg, bold in segs[1:]:
        if not seg:
            continue
        nr = par.add_run(seg)
        if base_rpr is not None:
            nr._element.insert(0, copy.deepcopy(base_rpr))
        if bold:
            nr.bold = True
        else:
            nr.bold = None


def wrap_toc_field(doc, first_toc_par: Paragraph, last_toc_par: Paragraph):
    """把手工目录文字包成 Word 的 TOC 域：显示不变，但按 F9/打开时可自动更新页码。

    为什么要做：本次内容增加后页码会变；手工目录文字不会自己更新，
    包成域以后 Word 能一键刷新（我们在保存前已经用 Word 更新过一次）。
    """
    from docx.oxml import OxmlElement
    lead = OxmlElement("w:r")
    b = OxmlElement("w:fldChar"); b.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve")
    it.text = ' TOC \\o "1-2" \\h \\z \\u '
    sp = OxmlElement("w:fldChar"); sp.set(qn("w:fldCharType"), "separate")
    for el in (b, it, sp):
        lead.append(el)
    first_toc_par._p.insert(0, lead)
    tail = OxmlElement("w:r")
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "end")
    tail.append(e)
    last_toc_par._p.append(tail)


def clone_par_after(par: Paragraph, text: str, style: str | None = None) -> Paragraph:
    new_p = copy.deepcopy(par._p)
    par._p.addnext(new_p)
    np = Paragraph(new_p, par._parent)
    if style:
        try:
            np.style = style
        except Exception:
            pass
    set_text(np, text)
    return np


def _separate_tables(tbl_el):
    """两张表紧挨着时 Word 会把它们**合并成一张**（实测：列宽不同会并成 6 个网格列，
    单元格文字看起来重复两遍）。所以在紧邻处插入一个空段落把它们隔开。"""
    from docx.oxml import OxmlElement
    nxt = tbl_el.getnext()
    if nxt is not None and nxt.tag == qn("w:tbl"):
        tbl_el.addnext(OxmlElement("w:p"))
    prv = tbl_el.getprevious()
    if prv is not None and prv.tag == qn("w:tbl"):
        tbl_el.addprevious(OxmlElement("w:p"))


def clone_table_after(par: Paragraph, src_tbl: Table, n_rows: int) -> Table:
    """复制一张已有表格的格式，跟在该段之后，并调整到 n_rows 行。"""
    new_tbl_el = copy.deepcopy(src_tbl._tbl)
    par._p.addnext(new_tbl_el)
    t = Table(new_tbl_el, par._parent)
    while len(t.rows) > n_rows:
        t._tbl.remove(t.rows[-1]._tr)
    while len(t.rows) < n_rows:
        t._tbl.append(copy.deepcopy(t.rows[-1]._tr))
    _separate_tables(new_tbl_el)
    return t


def append_rows(tbl: Table, rows_data):
    """在已有表格末尾追加若干行（复制最后一行的格式）。"""
    for vals in rows_data:
        tbl._tbl.append(copy.deepcopy(tbl.rows[-1]._tr))
        fill_row(tbl.rows[-1], vals)


def fill_row(row, values):
    for cell, val in zip(row.cells, values):
        set_text(cell.paragraphs[0], val)
        for extra in cell.paragraphs[1:]:
            set_text(extra, "")


def tbl_by_index(doc, idx: int) -> Table:
    return list(blocks(doc)) and [b for b in blocks(doc) if isinstance(b, Table)][idx - 1]


def find_par(doc, prefix: str) -> Paragraph:
    hits = [b for b in blocks(doc) if isinstance(b, Paragraph) and b.text.strip().startswith(prefix)]
    if len(hits) != 1:
        raise SystemExit("锚点不唯一/找不到（%d 个）：%r" % (len(hits), prefix[:40]))
    return hits[0]


def tab_fix(text: str) -> str:
    """修正报告路径笔误：`xxx。md` → `xxx.md`（正文里多处）。"""
    return re.sub(r"([\w\u4e00-\u9fff）\)])。md\b", r"\1.md", text)


